-- V6: degisiklik gecmisi (audit log). Proje, rapor, is kalemi ve takip kaydina API uzerinden yapilan her ekleme,
-- guncelleme ve silme bir olay olarak yazilir; olay degisen alanlari eski ve yeni degerleriyle tasir.
--
-- Gecmis yalnizca eklenir ve okunur. Kayit silinince gecmisi kalsin diye entity_id ve project_id yabanci anahtar
-- DEGILDIR. Yazan kisinin adi o anki haliyle saklanir; kullanici silinirse actor_id bosalir, ad kalir.

CREATE TABLE audit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id    BIGINT,
    actor_name  VARCHAR(255)             NOT NULL,
    action      VARCHAR(255)             NOT NULL,
    entity_type VARCHAR(255)             NOT NULL,
    entity_id   BIGINT                   NOT NULL,
    project_id  BIGINT                   NOT NULL,
    summary     VARCHAR(255)             NOT NULL,
    CONSTRAINT pk_audit_events PRIMARY KEY (id),
    CONSTRAINT fk_audit_events_actor FOREIGN KEY (actor_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_audit_events_action CHECK (action IN ('OLUSTURULDU', 'GUNCELLENDI', 'SILINDI')),
    CONSTRAINT ck_audit_events_entity_type CHECK (entity_type IN ('PROJE', 'RAPOR', 'IS_KALEMI', 'TAKIP_KAYDI'))
);

-- Proje sayfasindaki gecmis: en yeni once.
CREATE INDEX ix_audit_events_project ON audit_events (project_id, occurred_at DESC, id DESC);
-- Tek bir kaydin gecmisi.
CREATE INDEX ix_audit_events_entity ON audit_events (entity_type, entity_id);

-- Olayin degisen alanlari, alan sirasiyla. Uzun metinler 500 karakterde kesilir.
CREATE TABLE audit_event_changes (
    audit_event_id BIGINT       NOT NULL,
    sort_order     INTEGER      NOT NULL,
    field          VARCHAR(255) NOT NULL,
    old_value      VARCHAR(500),
    new_value      VARCHAR(500),
    CONSTRAINT pk_audit_event_changes PRIMARY KEY (audit_event_id, sort_order),
    CONSTRAINT fk_audit_event_changes_event FOREIGN KEY (audit_event_id) REFERENCES audit_events (id)
        ON DELETE CASCADE
);
