-- V5: projelerin risk, engel, karar ve aksiyon kayitlari (takip kayitlari).
--
-- Dort tur tek tabloda tutulur: alanlarin neredeyse tamami ortaktir, tur `type` kolonundan okunur.
-- Kayit haftaya degil projeye baglidir; bir risk kapanana kadar haftalar boyunca yasar.
-- Servisteki kurallarin veriyi tutarli birakanlari burada CHECK kisitiyla da guvenceye alinir.

CREATE TABLE tracking_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    project_id     BIGINT                   NOT NULL,
    type           VARCHAR(255)             NOT NULL,
    title          VARCHAR(255)             NOT NULL,
    description    VARCHAR(2000),
    risk_level     VARCHAR(255),
    impact         VARCHAR(2000),
    action_plan    VARCHAR(2000),
    assignee       VARCHAR(255),
    follow_up_date DATE,
    status         VARCHAR(255)             NOT NULL,
    closed_date    DATE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_tracking_items PRIMARY KEY (id),
    CONSTRAINT fk_tracking_items_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_tracking_items_type CHECK (type IN ('RISK', 'ENGEL', 'KARAR', 'AKSIYON')),
    CONSTRAINT ck_tracking_items_status CHECK (status IN ('ACIK', 'DEVAM_EDIYOR', 'KAPANDI')),
    CONSTRAINT ck_tracking_items_risk_level CHECK (risk_level IN ('DUSUK', 'ORTA', 'YUKSEK')),
    -- Risk seviyesi yalnizca risk ve engel kayitlarinda vardir, onlarda da zorunludur.
    CONSTRAINT ck_tracking_items_risk_level_by_type
        CHECK ((type IN ('RISK', 'ENGEL')) = (risk_level IS NOT NULL)),
    -- Kapanis tarihi yalnizca kapali kayitta bulunur (kapaninca yazilir, yeniden acilinca silinir).
    CONSTRAINT ck_tracking_items_closed_date
        CHECK ((status = 'KAPANDI') = (closed_date IS NOT NULL))
);

-- PostgreSQL yabanci anahtar kolonlarina otomatik indeks acmaz; proje detayi ve silme kontrolu bunu kullanir.
CREATE INDEX ix_tracking_items_project_id ON tracking_items (project_id);
