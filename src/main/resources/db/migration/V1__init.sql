-- V1: baslangic semasi.
-- H2 doneminde Hibernate'in entity'lerden urettigi semanin PostgreSQL karsiligidir.
-- Bundan sonra sema yalnizca yeni migration dosyalariyla (V2, V3, ...) degisir;
-- uygulama acilisinda Hibernate semayi yalnizca dogrular (ddl-auto: validate).
--
-- Enum kolonlari metin olarak tutulur (@Enumerated(EnumType.STRING)); CHECK kisitlari
-- izin verilen degerleri veritabani duzeyinde de garanti eder. Enum'a yeni deger
-- eklendiginde ilgili kisit da yeni bir migration ile guncellenmelidir.

CREATE TABLE users (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email     VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    role      VARCHAR(255) NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('PROJECT_MANAGER', 'CTO', 'ADMIN'))
);

CREATE TABLE projects (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(255)  NOT NULL,
    customer    VARCHAR(255),
    description VARCHAR(1000),
    status      VARCHAR(255)  NOT NULL,
    owner_id    BIGINT,
    CONSTRAINT pk_projects PRIMARY KEY (id),
    CONSTRAINT fk_projects_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT ck_projects_status
        CHECK (status IN ('PLANLANDI', 'DEVAM_EDIYOR', 'TAMAMLANDI', 'RISKLI', 'BLOKE'))
);

CREATE TABLE weekly_reports (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    project_id     BIGINT        NOT NULL,
    report_date    DATE          NOT NULL,
    week_number    INTEGER       NOT NULL,
    progress_stage VARCHAR(255)  NOT NULL,
    overall_status VARCHAR(255)  NOT NULL,
    risk_level     VARCHAR(255)  NOT NULL,
    done           VARCHAR(2000),
    planned        VARCHAR(2000),
    risks          VARCHAR(2000),
    note           VARCHAR(2000),
    CONSTRAINT pk_weekly_reports PRIMARY KEY (id),
    CONSTRAINT fk_weekly_reports_project FOREIGN KEY (project_id) REFERENCES projects (id),
    -- Bir proje bir hafta icin tek rapor alabilir (entity'deki adla ayni).
    CONSTRAINT uk_weekly_report_project_week UNIQUE (project_id, week_number),
    CONSTRAINT ck_weekly_reports_progress_stage
        CHECK (progress_stage IN ('ANALIZ', 'GELISTIRME', 'TEST', 'TAMAMLANDI')),
    CONSTRAINT ck_weekly_reports_overall_status
        CHECK (overall_status IN ('YOLUNDA', 'RISKLI', 'GECIKMELI', 'BLOKE')),
    CONSTRAINT ck_weekly_reports_risk_level
        CHECK (risk_level IN ('DUSUK', 'ORTA', 'YUKSEK'))
);

CREATE TABLE work_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    weekly_report_id BIGINT        NOT NULL,
    title            VARCHAR(255)  NOT NULL,
    description      VARCHAR(2000),
    assignee         VARCHAR(255),
    status           VARCHAR(255)  NOT NULL,
    planned_date     DATE,
    completed_date   DATE,
    CONSTRAINT pk_work_items PRIMARY KEY (id),
    CONSTRAINT fk_work_items_weekly_report FOREIGN KEY (weekly_report_id) REFERENCES weekly_reports (id),
    CONSTRAINT ck_work_items_status
        CHECK (status IN ('PLANLANDI', 'DEVAM_EDIYOR', 'TESTTE', 'TAMAMLANDI', 'GECIKTI', 'RISKLI', 'BLOKE'))
);

-- PostgreSQL yabanci anahtar kolonlarina otomatik indeks acmaz.
-- weekly_reports.project_id icin ayri indekse gerek yok: uk_weekly_report_project_week
-- bu kolonla basladigi icin ayni isi gorur.
CREATE INDEX ix_projects_owner_id ON projects (owner_id);
CREATE INDEX ix_work_items_weekly_report_id ON work_items (weekly_report_id);
